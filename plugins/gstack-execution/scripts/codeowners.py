#!/usr/bin/env python3
"""GA-013.2: CODEOWNERS is generated from the lane table's `owned` list, one home for who approves what.

  codeowners.py generate [--repo <path>]   write <repo>/.github/CODEOWNERS from the table in force
  codeowners.py check    [--repo <path>]   exit 1 when the committed file's rules differ from the table's

The table in force is the repository's own `.gstack/release-lanes.json`, else the plugin default, the same
rule peer_review.lane_table applies. `check` compares rules (pattern and owners, in order, since the last
match wins on GitHub), not comments, so a hand-edited rule fails and a reworded comment doesn't.
ponytail: owners in the table are written as given; GitHub validates them, this doesn't.
"""
import argparse
import json
import sys
from pathlib import Path

DEFAULT = Path(__file__).resolve().parents[1] / "skills" / "gstack-execution" / "references" / "release-lanes.json"
HEADER = ("# Generated by plugins/gstack-execution/scripts/codeowners.py from the lane table's `owned` list (GA-013).\n"
          "# Edit the table, then run `codeowners.py generate`; `codeowners.py check` fails on a hand edit.\n")


def table(repo):
    own = Path(repo) / ".gstack" / "release-lanes.json"
    return json.loads((own if own.exists() else DEFAULT).read_text(encoding="utf-8"))


def render(t):
    out = [HEADER]
    for entry in t.get("owned") or []:
        out.append(f"\n# {entry['purpose']}\n")
        out += [" ".join([p, *entry.get("owners", [])]) + "\n" for p in entry["paths"]]
    return "".join(out)


def rules(text):
    out = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            pattern, *owners = line.split()
            out.append((pattern, tuple(owners)))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=("generate", "check"))
    ap.add_argument("--repo", default=".")
    a = ap.parse_args(argv)
    path = Path(a.repo) / ".github" / "CODEOWNERS"
    t = table(a.repo)
    if "owned" not in t:   # review F1: an independently kept CODEOWNERS is never overwritten or judged
        print(f"codeowners {a.action}: the lane table in force has no owned list, so {path} isn't generated "
              "from it; skipped, the file left as it is")
        return 0
    want = render(t)
    if a.action == "generate":
        path.write_text(want, encoding="utf-8")
        print(f"wrote {path}: {len(rules(want))} rules")
        return 0
    have = rules(path.read_text(encoding="utf-8")) if path.exists() else []
    if not rules(want):
        print("codeowners check: the table has no owned rules; examined nothing", file=sys.stderr)
        return 1
    if have != rules(want):
        extra = [r for r in have if r not in rules(want)]
        missing = [r for r in rules(want) if r not in have]
        print(f"codeowners check: {path} differs from the table (run `codeowners.py generate`): "
              f"not in the table {extra}, missing {missing}" + ("" if extra or missing else ", order differs"), file=sys.stderr)
        return 1
    print(f"codeowners check: {len(have)} rules match the table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
